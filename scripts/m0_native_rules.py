"""Deterministic PCI source-candidate table for native Ryzova pc64 diagnostics.

Only converts validated M0 candidate metadata; never provides a driver binder.
USB rules remain in host-only inventory until a separate native USB adapter.
"""
import argparse
from pathlib import Path
import sys

from m0_device_registry import CandidateIndex, read_json

OUTPUT = "sys/src/9/port/ryzovapcirules.h"
REGISTRY = "ryzova/drivers/m0-device-registry.json"
FIRMWARE = "ryzova/drivers/m0-firmware-manifest.json"


def generate(root):
    data = read_json(root / REGISTRY)
    firmware = read_json(root / FIRMWARE)
    index = CandidateIndex(data, firmware, root)
    index.verify_pc64_configuration(root)
    lines = [
        "/* SPDX-License-Identifier: AGPL-3.0-only */",
        "/* GENERATED by scripts/m0_native_rules.py; all rules are source candidates. */",
        "/* Do not treat a match as a driver attachment or verified hardware. */",
        "#ifndef RYZOVA_PCI_CANDIDATE_RULES_H",
        "#define RYZOVA_PCI_CANDIDATE_RULES_H",
        "",
        "static Rzdrvrule rzpcirules[] = {",
    ]
    names = []
    for row in index.rules:
        if row["bus"] != "pci":
            continue
        selector = next(r["selector"] for r in data["rules"] if r["id"] == row["id"])
        if row["kind"] == "exact":
            kind = "RzruleExact"
            vendor = int(selector["vendor_id"], 16)
            device = int(selector["device_id"], 16)
            clas = sub = proto = 0
        else:
            vendor = device = 0
            clas = int(selector["class"], 16)
            sub = int(selector["subclass"], 16)
            if "protocol" in selector:
                proto = int(selector["protocol"], 16)
                kind = "RzruleClassProtocol"
            else:
                proto = 0
                kind = "RzruleClass"
        lines.append(
            "\t{RzbusPci, %s, 0x%04x, 0x%04x, 0x%02x, 0x%02x, 0x%02x, %d, %d},"
            % (kind, vendor, device, clas, sub, proto, row["lo"], row["hi"])
        )
        names.append(row["id"])
    if not names:
        raise ValueError("native PCI table must not be empty")
    lines += ["};", "", "static char *rzpciruleids[] = {"]
    for name in names:
        lines.append('\t"%s",' % name)
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="verify checked-in native table matches review metadata")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        generated = generate(root)
        target = root / OUTPUT
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != generated:
                raise ValueError("native PCI table is out of sync with reviewed M0 registry")
            print("native PCI rules match reviewed source registry")
        else:
            target.write_text(generated, encoding="utf-8")
            print("wrote", target)
    except (OSError, ValueError) as e:
        parser.exit(1, "M0 native rules rejected: " + str(e) + "\n")


if __name__ == "__main__":
    main()
