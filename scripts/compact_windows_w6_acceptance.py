"""Fail-closed W6 native AMD64/QEMU *bounded profile* evidence validator.

A hosted test or a copied historical receipt is not native evidence. The caller
must supply a report and all four serial logs from the SAME source-built run.
No claim of physical power-loss, ARM64, arbitrary Windows app or boot-hjfs
SIGKILL recovery can be inferred from this qualification.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re

from compact_windows_w2 import ROOT
from compact_windows_w4 import PAYLOAD
from compact_windows_w6_native import (
    PIN, case_specs, fault_specs, parse_cases, standalone,
    verify_dedicated_resource_reboot, verify_fault_fixture,
)

SCHEMA="compact-windows-w6-native/v1"
ACCEPTANCE_SCHEMA="compact-windows-w6-virtual-acceptance/v1"
CASE_NAMES=set(case_specs())|set(fault_specs())
TRUE_FLAGS=(
    "native_amd64_qemu_qualified",
    "native_9p_namespace_verified",
    "reboot_persistence_verified",
    "dedicated_resource_sigkill_persistence_qualified",
    "native_file_flush_qualified",
    "barrier_local_only_verified",
    "qemu_sigkill_persistence_verified",
    "storage_flush_failure_and_sticky_error_verified",
)
FALSE_FLAGS=(
    "boot_root_sigkill_persistence_qualified",
    "full_w6_complete",
    "physical_hardware_qualified",
    "arm64_windows_qualified",
    "general_windows_compatibility",
)
REQUIRED_LOGS=("build-serial.log","fresh-serial.log",
               "reboot-serial.log","fault-serial.log")


def check(report, logs, source_sha):
    if not isinstance(report,dict) or report.get("schema")!=SCHEMA:
        raise ValueError("wrong native receipt schema")
    if not isinstance(source_sha,str) or re.fullmatch(r"[0-9a-f]{40}",source_sha) is None:
        raise ValueError("missing exact tested source commit")
    if report.get("source_commit")!=source_sha:
        raise ValueError("receipt was not generated by the checked-out native commit")
    if report.get("bootstrap_image_gzip_sha256")!=PIN:
        raise ValueError("unexpected bootstrap provenance")
    if report.get("flush_evidence_scope")!=(
        "dedicated QEMU virtio-SCSI disk; pinned cw-hjfs ACK after dirty cache drain and SYNCHRONIZE CACHE; no physical power-loss claim"):
        raise ValueError("unqualified storage profile")
    for field in TRUE_FLAGS:
        if report.get(field) is not True:
            raise ValueError("native proof incomplete: "+field)
    for field in FALSE_FLAGS:
        if report.get(field) is not False:
            raise ValueError("unsupported qualification falsely advertised: "+field)
    for key in ("source_archive_sha256","kernel_sha256","runtime_sha256",
                "bootstrap_image_sha256","resource_server_sha256",
                "durable_file_sha256","storage_fault_config_sha256"):
        value=report.get(key)
        if not isinstance(value,str) or re.fullmatch("[0-9a-f]{64}",value) is None:
            raise ValueError("missing native source/fixture SHA256: "+key)
    if report["durable_file_sha256"]!=hashlib.sha256(PAYLOAD).hexdigest():
        raise ValueError("native durable file differs from frozen W4 reference")
    if report.get("file_sha256")!=hashlib.sha256(b"FLEX_WINDOWS_W4_FILE_OK\n").hexdigest():
        raise ValueError("ordinary W4 file hash differs from frozen reference")
    hashes=report.get("fixture_sha256")
    if not isinstance(hashes,dict):
        raise ValueError("missing frozen PE fixture provenance")
    for key in ("file","api","heap-limit","io-limit","handle-limit","ramfs-io"):
        if re.fullmatch("[0-9a-f]{64}",hashes.get(key,"")) is None:
            raise ValueError("missing frozen fixture checksum: "+key)
    if not isinstance(logs,dict) or set(logs)!=set(REQUIRED_LOGS):
        raise ValueError("incomplete native QEMU serial logs")
    if any(not isinstance(logs[k],bytes) or not logs[k] for k in REQUIRED_LOGS):
        raise ValueError("empty/untrusted native QEMU serial log")

    build,fresh,reboot,fault=(logs[n] for n in REQUIRED_LOGS)
    if not all(standalone(build,n) for n in (
            "CW_NATIVE_BUILD_OK","CW_KERNEL_BUILD_OK","CW_KERNEL_COPY_OK")):
        raise ValueError("source-built runtime/kernel not shown")
    if not all(standalone(fresh,n) for n in (
            "CW_BARRIER_LOCAL_ONLY_OK","CW_BARRIER_SERVICE_OK",
            "CW_NAMESPACE_ISOLATION_OK","CW_RUNTIME_DONE")):
        raise ValueError("fresh guest namespace/resource/barrier evidence missing")
    if b"Ryzova Kernel 0.1.0-dev" not in fresh:
        raise ValueError("native kernel did not identify itself")
    if not standalone(fresh,"CW_CASE_durable_END"):
        raise ValueError("no completed MSVC W4 durability guest case")
    verify_dedicated_resource_reboot(
        reboot,report["runtime_sha256"],report["durable_file_sha256"])
    verify_fault_fixture(fault,hashes["file"])
    if b"Ryzova Kernel 0.1.0-dev" not in fault:
        raise ValueError("no native kernel identity in injected fault boot")
    if not all(standalone(fault,n) for n in (
            "CW_FAULT_MOUNTED","CW_FAULT_CLEAN_OK")):
        raise ValueError("storage failure probe did not mount and prepare the disk")
    actual={}
    actual.update(parse_cases(fresh,case_specs()))
    actual.update(parse_cases(fault,fault_specs()))
    if set(actual)!=CASE_NAMES or len(CASE_NAMES)!=22:
        raise ValueError("not all 22 native cases exercised")
    if actual!=report.get("cases"):
        raise ValueError("native receipt does not match original QEMU serial cases")
    durable=actual["durable"]
    if (durable.get("flushes")!=2 or
            durable.get("code")!=0x23456789 or
            durable.get("calls",{}).get("FlushFileBuffers",0)<2):
        raise ValueError("two acknowledged real W4 flushes not proven")
    for name in fault_specs():
        case=actual[name]
        if (case.get("error")!=1117 or case.get("flushes")!=0 or
                case.get("code")!=103 or
                case.get("calls",{}).get("FlushFileBuffers",0)<1):
            raise ValueError("injected storage fault was acknowledged: "+name)
    if actual["loop"].get("steps")!=1024 or actual["handle-limit"].get("peak_handles")!=30:
        raise ValueError("bounded instruction/handle enforcement not observed")
    return {
        "schema":ACCEPTANCE_SCHEMA,
        "source_commit":source_sha,
        "bounded_amd64_qemu_22_case_qualified":True,
        "native_cases":len(actual),
        "resource_file_sha256":report["durable_file_sha256"],
        "native_resource_flush_verified":True,
        "qemu_sigkill_resource_recovery_verified":True,
        "sticky_storage_failure_verified":True,
        "full_w6_complete":False,
        "physical_hardware_qualified":False,
        "boot_filesystem_hardcut_qualified":False,
        "general_windows_compatibility":False,
        "merge_authorized":False,
        "scope":"Source-built native AMD64 QEMU, bounded Windows PE/CRT and dedicated virtual virtio-SCSI 9P resource; no physical hardware or power-loss qualification",
    }


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("evidence",type=Path)
    parser.add_argument("--source-sha",required=True)
    args=parser.parse_args()
    evidence=args.evidence
    report=json.loads((evidence/"qualification.json").read_text())
    logs={name:(evidence/name).read_bytes() for name in REQUIRED_LOGS}
    result=check(report,logs,args.source_sha)
    (evidence/"virtual-acceptance.json").write_text(
        json.dumps(result,indent=2,sort_keys=True)+"\n")
    print(json.dumps(result,indent=2,sort_keys=True))


if __name__=="__main__":
    main()
